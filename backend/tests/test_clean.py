from app.processing.clean import MAX_CLEAN_CHARS, clean_body

BUG_TEMPLATE = """<!-- ⚠️⚠️ Do Not Delete This! bug_report_template ⚠️⚠️ -->
<!-- 🔎 Search existing issues to avoid creating duplicates. -->
Does this issue occur when all extensions are disabled?: Yes

- VS Code Version: 1.137.0
- OS Version: Windows 11

Steps to Reproduce:

1. Open the terminal panel.
2. Split the terminal.
3.

The split pane closes immediately.
"""

EMPTY_FEATURE_TEMPLATE = """<!-- ⚠️⚠️ Do Not Delete This! feature_request_template ⚠️⚠️ -->
<!-- Please search existing issues to avoid creating duplicates. -->

<!-- Describe the feature you'd like. -->
"""


def test_removes_template_comments_and_environment_lines() -> None:
    cleaned = clean_body(BUG_TEMPLATE)

    assert cleaned == (
        "Steps to Reproduce:\n\n"
        "1. Open the terminal panel.\n"
        "2. Split the terminal.\n\n"
        "The split pane closes immediately."
    )


def test_untouched_template_becomes_empty() -> None:
    assert clean_body(EMPTY_FEATURE_TEMPLATE) == ""
    assert clean_body(None) == ""


def test_keeps_only_the_first_line_of_code_blocks() -> None:
    body = (
        "Crash on start:\n\n"
        "```text\n"
        "TypeError: cannot read properties of undefined\n"
        "    at activate (ext.js:10)\n"
        "    at run (host.js:99)\n"
        "```\n\n"
        "Happens every time."
    )

    assert clean_body(body) == (
        "Crash on start:\n\nTypeError: cannot read properties of undefined\n\nHappens every time."
    )


def test_drops_an_unclosed_code_block_to_the_end() -> None:
    assert clean_body("Log output:\n```\nline one\nline two") == "Log output:"


def test_single_line_fences_keep_their_text() -> None:
    assert (
        clean_body("Run ```code --verbose``` and it hangs.") == "Run code --verbose and it hangs."
    )


def test_removes_reporter_details_tables_images_and_html() -> None:
    body = (
        "Type: <b>Bug</b>\n\n"
        "Icons vanish from the activity bar.\n\n"
        '<img width="200" alt="Image" src="https://example.com/a.png">\n'
        "![screenshot](https://example.com/b.png)\n\n"
        "| Item | Value |\n|---|---|\n| CPU | x |\n\n"
        "<details><summary>Extensions (3)</summary>\n\nextension list\n</details>\n"
        "<!-- generated by issue reporter -->"
    )

    assert clean_body(body) == "Icons vanish from the activity bar.\n\n[image]\n[image]"


def test_keeps_link_text_and_strips_heading_markers() -> None:
    body = "## Expected behavior\nSee [the docs](https://example.com) for<br>details."

    assert clean_body(body) == "Expected behavior\nSee the docs for\ndetails."


def test_truncates_long_text_on_a_word_boundary() -> None:
    cleaned = clean_body("word " * 2000)

    assert len(cleaned) <= MAX_CLEAN_CHARS + 2
    assert cleaned.endswith("word …")


def test_handles_code_blocks_inside_quoted_replies() -> None:
    body = (
        "> I use this workaround\n"
        ">\n"
        "> ```\n"
        "> call create_session\n"
        "> with worktree enabled\n"
        "> ```\n\n"
        "Please support it directly."
    )

    assert clean_body(body) == (
        "I use this workaround\n\ncall create_session\n\nPlease support it directly."
    )


def test_handles_fences_longer_than_three_backticks() -> None:
    body = 'Settings:\n````json\n{"limit": 1}\n{"other": 2}\n````\nStill ignored.'

    assert clean_body(body) == 'Settings:\n{"limit": 1}\nStill ignored.'


def test_removes_bold_environment_lines() -> None:
    body = "**VS Code version:** 1.137.0\n**OS version:** Windows\n\nThe webview crashes."

    assert clean_body(body) == "The webview crashes."


def test_removes_stray_backticks_and_empty_task_boxes() -> None:
    assert clean_body("Limit is 200000````\n\n- [ ]\n\nThanks") == "Limit is 200000\n\nThanks"
